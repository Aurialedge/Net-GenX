import { AlertCircle } from 'lucide-react'
import { Spinner } from '@/components/ui/spinner'

const SOURCE_LABEL = { gemini: 'Generated by Gemini', rules: 'Built-in playbook' }

function AssistantMessage({ message }) {
  const source = SOURCE_LABEL[message.source]
  return (
    <div className="bg-card max-w-[46rem] rounded-xl border p-4 shadow-xs">
      <p className="text-muted-foreground mb-2 text-xs font-medium">Assistant</p>
      <ol className="space-y-2.5 text-sm leading-relaxed">
        {message.steps.map((step, i) => (
          <li key={i} className="flex gap-3">
            <span className="text-muted-foreground w-5 shrink-0 text-right font-mono tabular">{step.key}.</span>
            <span className="min-w-0 break-words">{step.text}</span>
          </li>
        ))}
      </ol>
      {source && <p className="text-muted-foreground mt-3 border-t pt-2.5 text-xs">{source}</p>}
    </div>
  )
}

function UserMessage({ message }) {
  return (
    <div className="ml-auto max-w-[85%] sm:max-w-[32rem]">
      <p className="sr-only">You asked</p>
      <div className="bg-primary text-primary-foreground rounded-xl px-4 py-2.5 text-sm leading-relaxed break-words whitespace-pre-wrap">
        {message.text}
      </div>
    </div>
  )
}

function ErrorMessage({ message }) {
  return (
    <div
      role="alert"
      className="border-danger/30 bg-danger-muted text-danger-foreground flex max-w-[46rem] gap-2.5 rounded-xl border px-4 py-3 text-sm"
    >
      <AlertCircle className="mt-0.5 size-4 shrink-0" aria-hidden />
      <p className="min-w-0 break-words">{message.text}</p>
    </div>
  )
}

/**
 * The chat transcript. Messages:
 *   { id, role: 'user', text }
 *   { id, role: 'assistant', steps: [{ key, text }], source, riskScore }
 *   { id, role: 'error', text }
 */
export function Conversation({ messages, pending, endRef }) {
  return (
    <div role="log" aria-live="polite" aria-relevant="additions" aria-label="Conversation" className="space-y-4">
      {messages.map((m) =>
        m.role === 'user' ? (
          <UserMessage key={m.id} message={m} />
        ) : m.role === 'error' ? (
          <ErrorMessage key={m.id} message={m} />
        ) : (
          <AssistantMessage key={m.id} message={m} />
        ),
      )}
      {pending && (
        <div className="text-muted-foreground flex items-center gap-2 px-1 text-sm">
          <Spinner aria-hidden="true" role="presentation" />
          <span>Preparing your steps…</span>
        </div>
      )}
      <div ref={endRef} aria-hidden />
    </div>
  )
}
