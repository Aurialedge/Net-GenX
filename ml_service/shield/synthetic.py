"""
Layer 3 - Synthetic Artifact Detection.

Text: stylometric signals that separate LLM-written "humanised" chat from real
people typing on a phone - low burstiness (uniform sentence lengths), stock LLM
phrasing, flawless punctuation and capitalisation with no typos/slang, high
lexical polish, and the greeting -> validation -> question template.

Media: provenance markers embedded by generators (Stable Diffusion / ComfyUI
PNG chunks, Midjourney/DALL-E/Firefly tags, C2PA "trainedAlgorithmicMedia"),
missing camera EXIF, and voice-clone / TTS tool signatures in audio metadata.

These are heuristics, not proof: a polished human writer can score high, so
the engine treats this layer as an *amplifier* of the other layers rather than
a standalone verdict.
"""
import math
import re
import statistics
import zlib

from preprocessor import normalize
from .common import layer_result, rx, count_matches

LLM_PHRASES = rx(
    r"\bi hope (?:this|my) message finds you\b", r"\bi hope you(?:'re| are) (?:having|doing) (?:a )?(?:wonderful|great|well)",
    r"\bfelt compelled to\b", r"\bi couldn'?t help but notice\b", r"\bgenuinely\b", r"\btruly\b", r"\bdeeply\b",
    r"\bit'?s (?:truly )?(?:rare|refreshing) to\b", r"\bi(?:'d| would) love to (?:hear|learn|know|connect)\b",
    r"\bout of (?:pure )?curiosity\b", r"\bfascinating\b", r"\binvaluable\b", r"\bwould be (?:invaluable|greatly appreciated)\b",
    r"\bi completely understand\b", r"\babsolutely\b", r"\bcertainly!", r"\bdelve\b", r"\bjourney\b", r"\bnavigat(?:e|ing)\b",
    r"\bat your earliest convenience\b", r"\bkindly\b", r"\bplease (?:feel free|don'?t hesitate)\b", r"\bthat sounds\b",
    r"\bi appreciate you (?:sharing|opening up)\b", r"\bmeans (?:a lot|so much) to me\b", r"\bin today'?s\b",
    r"\bas an ai\b", r"\bi'?m (?:just )?an ai\b", r"\btestament to\b", r"\bresonat\w+\b", r"\bfoster\w*\b",
)
HUMAN_MARKERS = rx(
    r"\b(?:u|ur|r|pls|plz|thx|tnx|bcoz|coz|bhai|yaar|haan|nahi|kya|hai|kal|acha|ok+|lol|hmm+|ya+|na)\b",
    r"\b\w*(\w)\1\1+\w*\b",          # sooo, heyyy
    r"(?<![.!?])\s+i\s+",             # lower-case "i"
    r"\.\.\.", r"\?\?+", r"!!+",
)
AI_MEDIA_MARKERS = {
    b"parameters": "stable_diffusion_png_parameters", b"Steps:": "stable_diffusion_settings", b"ComfyUI": "comfyui_workflow",
    b"\"prompt\"": "embedded_generation_prompt", b"Midjourney": "midjourney", b"DALL-E": "dall_e", b"DALL\xc2\xb7E": "dall_e",
    b"Adobe Firefly": "adobe_firefly", b"trainedAlgorithmicMedia": "c2pa_ai_generated_assertion", b"c2pa": "c2pa_manifest",
    b"NovelAI": "novelai", b"Imagen": "google_imagen", b"SynthID": "synthid_watermark_tag", b"ElevenLabs": "elevenlabs_tts",
    b"Resemble": "resemble_voice_clone", b"PlayHT": "playht_tts", b"Lavf": "ffmpeg_reencoded", b"Generated by": "generator_tag",
}


def _sentences(t):
    return [s for s in re.split(r"(?<=[.!?])\s+", t) if len(s.split()) >= 2]


def analyze_text(text, **_):
    t = normalize(text)
    words = re.findall(r"[A-Za-z']+", t)
    if len(words) < 12:
        return layer_result(3, "Synthetic Artifact Detection", 0, ["insufficient_text_for_stylometry"],
                            {"words": len(words)}, verdict="INCONCLUSIVE", confidence=0.2)

    sents = _sentences(t) or [t]
    lens = [len(s.split()) for s in sents]
    burstiness = statistics.pstdev(lens) / statistics.mean(lens) if len(lens) > 1 else 0.5
    llm_hits = count_matches(LLM_PHRASES, t)
    human_hits = count_matches(HUMAN_MARKERS, t)
    ttr = len({w.lower() for w in words}) / len(words)
    avg_wlen = sum(len(w) for w in words) / len(words)
    caps_ok = sum(1 for s in sents if s[:1].isupper()) / len(sents)
    ends_ok = 1.0 if re.search(r"[.!?]$", t) else 0.0
    comp_ratio = len(zlib.compress(t.encode())) / max(1, len(t.encode()))
    template = bool(re.match(r"^(?:hi|hello|hey|good (?:morning|evening)|dear)\b", t, re.I)) and "?" in t and llm_hits > 0
    exclaim_polite = len(re.findall(r"!\s", t + " ")) >= 1 and llm_hits >= 1

    # Hand-calibrated log-odds (positive => machine-like)
    z = -1.4
    z += 0.9 * min(llm_hits, 4)
    z -= 0.8 * min(human_hits, 4)
    z += 1.1 * (1 if len(lens) >= 3 and burstiness < 0.35 else 0)
    z += 0.6 * caps_ok * ends_ok
    z += 0.5 * (1 if avg_wlen > 4.6 else 0)
    z += 0.4 * (1 if template else 0)
    z += 0.3 * (1 if exclaim_polite else 0)
    z += 0.3 * (1 if 0.62 <= ttr <= 0.9 and len(words) > 25 else 0)
    p = 1 / (1 + math.exp(-z))

    signals = []
    if llm_hits:
        signals.append(f"llm_stock_phrasing x{llm_hits}")
    if len(lens) >= 3 and burstiness < 0.35:
        signals.append(f"low_burstiness({burstiness:.2f})")
    if human_hits == 0 and caps_ok == 1 and ends_ok:
        signals.append("flawless_mechanics_no_informal_markers")
    if template:
        signals.append("greeting_validation_question_template")
    if human_hits:
        signals.append(f"human_informality_markers x{human_hits}")
    return layer_result(
        3, "Synthetic Artifact Detection", 100 * p, signals,
        {"synthetic_probability": round(p, 3), "burstiness": round(burstiness, 3), "type_token_ratio": round(ttr, 3),
         "avg_word_length": round(avg_wlen, 2), "compression_ratio": round(comp_ratio, 3),
         "llm_phrase_hits": llm_hits, "human_marker_hits": human_hits, "sentences": len(lens)},
        verdict="LIKELY_AI_GENERATED" if p >= 0.7 else "POSSIBLY_AI_GENERATED" if p >= 0.45 else "LIKELY_HUMAN",
        confidence=min(0.85, 0.4 + len(words) / 150))


def analyze_media(filename, content: bytes, mime_type=""):
    head = content[:2_000_000]
    found = sorted({label for marker, label in AI_MEDIA_MARKERS.items() if marker in head})
    name = (filename or "").lower()
    is_image = mime_type.startswith("image") or name.endswith((".jpg", ".jpeg", ".png", ".webp", ".heic"))
    is_audio = mime_type.startswith("audio") or name.endswith((".mp3", ".wav", ".m4a", ".ogg", ".aac", ".opus"))
    is_video = mime_type.startswith("video") or name.endswith((".mp4", ".mov", ".mkv", ".avi", ".webm"))
    signals = [f"generator_marker:{f}" for f in found]
    score = 0.0
    strong = {"stable_diffusion_png_parameters", "stable_diffusion_settings", "comfyui_workflow", "embedded_generation_prompt",
              "midjourney", "dall_e", "adobe_firefly", "c2pa_ai_generated_assertion", "novelai", "google_imagen",
              "synthid_watermark_tag", "elevenlabs_tts", "resemble_voice_clone", "playht_tts"}
    if strong & set(found):
        score = 92
    elif found:
        score = 35
    if is_image and head[:3] == b"\xff\xd8\xff":
        has_exif = b"Exif" in head[:65536]
        has_camera = has_exif and any(k in head[:65536] for k in (b"Canon", b"NIKON", b"Apple", b"samsung", b"SONY", b"Xiaomi", b"OnePlus", b"Google", b"motorola", b"vivo", b"OPPO", b"realme"))
        if not has_exif:
            signals.append("no_exif_metadata(stripped_or_synthetic)")
            score = max(score, 30)
        elif has_camera:
            signals.append("camera_exif_present")
    if is_image and head[:8] == b"\x89PNG\r\n\x1a\n" and not found and len(content) > 200_000:
        signals.append("large_png_without_camera_provenance")
        score = max(score, 20)
    kind = "image" if is_image else "audio" if is_audio else "video" if is_video else "other"
    return layer_result(
        3, "Synthetic Artifact Detection", score, signals,
        {"media_type": kind, "generator_markers": found, "bytes_scanned": len(head),
         "note": "Metadata/provenance check only; absence of markers does not prove authenticity."},
        verdict="AI_GENERATED_MEDIA" if score >= 80 else "UNVERIFIED_PROVENANCE" if score >= 25 else "NO_SYNTHETIC_MARKERS",
        confidence=0.9 if score >= 80 else 0.4)
